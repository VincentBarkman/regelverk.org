// Runs after `vite build`. adapter-cloudflare writes its generated worker to
// wrangler's `main` (worker/entry.js), overwriting whatever is there — so the
// /en HTML transform can't live in that file. We move the generated worker to
// worker/_generated.js and emit worker/entry.js as a thin wrapper around it.
//
// Why the wrapper exists: SvelteKit serves a *rerouted* prerendered path
// before hooks run (respond.js fast path), so `/en/...` requests for
// prerendered pages get the base-locale HTML verbatim — including relative
// `../_app` asset URLs that resolve to `/en/_app/...` and 404, which kills
// hydration. Hooks cannot intercept that path, so we post-process the
// response here: make the asset URLs absolute and fix the baked `lang`.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const ENTRY = 'worker/entry.js';
const GENERATED = 'worker/_generated.js';

const code = readFileSync(ENTRY, 'utf8');
if (code.includes('server.respond')) {
	writeFileSync(GENERATED, code);
} else if (!existsSync(GENERATED)) {
	throw new Error('wrap-worker: entry.js is already a wrapper and _generated.js is missing');
}

writeFileSync(
	ENTRY,
	`// Generated by scripts/wrap-worker.mjs — do not edit, see that file.
import worker from './_generated.js';

const LOCALES = ['en'];

export default {
	async fetch(request, env, ctx) {
		const res = await worker.fetch(request, env, ctx);

		const { pathname } = new URL(request.url);
		const segment = pathname.split('/')[1];
		if (!LOCALES.includes(segment)) return res;
		if (!res.headers.get('content-type')?.includes('text/html')) return res;

		const headers = new Headers(res.headers);
		// ASSETS may serve pre-compressed bodies; res.text() yields decoded text,
		// so drop the now-wrong headers before re-wrapping.
		headers.delete('content-encoding');
		headers.delete('content-length');

		const html = (await res.text())
			.replace(/(\\.\\.?\\/)+_app\\//g, '/_app/')
			.replace('<html lang="sv"', \`<html lang="\${segment}"\`);

		return new Response(html, {
			status: res.status,
			statusText: res.statusText,
			headers
		});
	}
};
`
);
console.log('wrap-worker: wrapped', ENTRY);
